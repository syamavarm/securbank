const EMPTY_TEXT = 'No Synopsys solution areas matched this request.';
const ERROR_TEXT = 'Solution areas could not be loaded. Ask again in the chat.';
const DELIVERY_ERROR_TEXT = 'The request could not be sent. Try again.';
const REQUEST_FIELDS = [
  ['engineering_goal', 'Goal', true],
  ['industry', 'Industry', false],
  ['lifecycle_stage', 'Stage', false],
  ['current_environment', 'Environment', false],
];

let instanceCount = 0;

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined && text !== null) node.textContent = text;
  return node;
}

function icon(className) {
  const node = el('span', className);
  node.setAttribute('aria-hidden', 'true');
  return node;
}

function hasText(value) {
  if (typeof value === 'string') return value.trim() !== '';
  return value !== null && value !== undefined;
}

function safeUrl(value) {
  if (typeof value !== 'string' || !value.trim()) return null;
  try {
    const url = new URL(value.trim());
    return url.protocol === 'https:' ? url.href : null;
  } catch {
    return null;
  }
}

function plural(word, count) {
  if (count === 1) return word;
  if (/[^aeiou]y$/i.test(word)) return `${word.slice(0, -1)}ies`;
  return `${word}s`;
}

function groupsOf(records) {
  const groups = [];
  records.forEach((record, index) => {
    if (!hasText(record.solution_category)) return;
    const category = String(record.solution_category);
    let group = groups.find((g) => g.category === category);
    if (!group) {
      group = { category, count: 0, first: index };
      groups.push(group);
    }
    group.count += 1;
  });
  return groups;
}

function countText(records, groups) {
  const total = `${records.length} ${plural('area', records.length)}`;
  if (!groups.length) return total;
  const parts = groups.map((g) => `${g.count} ${plural(g.category, g.count).toLowerCase()}`);
  return `${total}: ${parts.join(', ')}`;
}

function nameOf(record) {
  return record && hasText(record.name) ? String(record.name) : '';
}

function buildHeader(args, records, groups, state) {
  const header = el('header', 'widget-head');
  header.append(el('h1', 'widget-title', 'Synopsys solution areas'));
  if (state === 'ok' && records.length) {
    header.append(el('p', 'widget-count', countText(records, groups)));
  }
  const items = REQUEST_FIELDS.filter(([key]) => hasText(args[key]));
  if (items.length) {
    const dl = el('dl', 'request');
    items.forEach(([key, label, wide]) => {
      const item = el('div', wide ? 'request-item request-goal' : 'request-item');
      item.append(el('dt', '', label), el('dd', '', String(args[key])));
      dl.append(item);
    });
    header.append(dl);
  }
  return header;
}

function buildCard(record, index, prefix, checked) {
  const card = el('li', 'area-card');
  card.id = `${prefix}-area-${index + 1}`;
  const name = nameOf(record);

  const input = el('input', 'area-pick');
  input.type = 'radio';
  input.name = `${prefix}-area`;
  input.id = `${prefix}-pick-${index + 1}`;
  input.value = hasText(record.id) ? String(record.id) : String(index);
  input.checked = checked;
  input.dataset.index = String(index);

  const head = el('label', 'area-head');
  head.htmlFor = input.id;
  const src = safeUrl(record.image_url);
  if (src) {
    const img = el('img', 'area-thumb');
    img.src = src;
    img.alt = name;
    img.width = 64;
    img.height = 64;
    img.decoding = 'async';
    head.append(img);
  } else {
    head.append(icon('area-thumb'));
  }
  const title = el('span', 'area-title');
  if (name) title.append(el('span', 'area-name', name));
  if (hasText(record.solution_category)) {
    title.append(el('span', 'badge', String(record.solution_category)));
  }
  const check = icon('area-check');
  check.append(icon('check-mark'));
  head.append(title, check);
  card.append(input, head);

  if (hasText(record.description)) {
    card.append(el('p', 'area-desc', String(record.description)));
  }
  const href = safeUrl(record.source_url);
  if (href) {
    const link = el('a', 'area-link', 'Explore on synopsys.com');
    link.href = href;
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    if (name) link.append(el('span', 'visually-hidden', `: ${name}`));
    link.append(icon('link-icon'));
    card.append(link);
  }
  return card;
}

function isLive(bridge) {
  return Boolean(bridge?.isConnected) && bridge.hostContext?.preview !== true;
}

async function send(bridge, prompt, status) {
  if (!bridge?.isConnected) return;
  status.textContent = '';
  try {
    const result = await bridge.sendMessage(prompt);
    if (result?.isError === true) status.textContent = DELIVERY_ERROR_TEXT;
  } catch {
    status.textContent = DELIVERY_ERROR_TEXT;
  }
}

function buildJump(groups, prefix, carousel, track) {
  const jump = el('nav', 'jump');
  jump.setAttribute('aria-label', 'Jump to a group');
  groups.forEach((group) => {
    const pill = el('a', 'jump-pill', plural(group.category, 2));
    pill.href = `#${prefix}-area-${group.first + 1}`;
    pill.append(el('span', 'jump-count', String(group.count)));
    pill.addEventListener('click', (event) => {
      event.preventDefault();
      const card = track.children[group.first];
      if (!card) return;
      const offset = card.getBoundingClientRect().left
        - carousel.getBoundingClientRect().left + carousel.scrollLeft;
      const pad = parseFloat(getComputedStyle(track).paddingLeft) || 0;
      carousel.scrollTo({ left: Math.max(0, offset - pad) });
    });
    jump.append(pill);
  });
  return jump;
}

function render(block, bridge, data, state) {
  instanceCount += 1;
  const prefix = `mes${instanceCount}`;
  const args = data && typeof data.arguments === 'object' && data.arguments ? data.arguments : {};
  const records = Array.isArray(data?.records)
    ? data.records.filter((r) => r && typeof r === 'object')
    : [];
  const groups = groupsOf(records);
  const nodes = [buildHeader(args, records, groups, state)];

  if (state === 'error') {
    nodes.push(el('p', 'notice', ERROR_TEXT));
    block.replaceChildren(...nodes);
    return;
  }

  const status = el('p', 'status');
  status.setAttribute('role', 'status');
  let selected = 0;
  let selectedName = null;

  if (records.length) {
    const carousel = el('div', 'carousel');
    carousel.setAttribute('role', 'region');
    carousel.setAttribute('aria-label', 'Solution areas, scroll sideways');
    carousel.tabIndex = 0;
    const track = el('ol', 'track');
    records.forEach((record, index) => {
      track.append(buildCard(record, index, prefix, index === 0));
    });
    carousel.append(track);

    if (groups.length) nodes.push(buildJump(groups, prefix, carousel, track));

    const fieldset = el('fieldset', 'areas');
    fieldset.append(el('legend', 'visually-hidden', 'Choose a solution area'), carousel);
    nodes.push(fieldset);

    fieldset.addEventListener('change', (event) => {
      const index = Number(event.target?.dataset?.index);
      if (!Number.isInteger(index) || !records[index]) return;
      selected = index;
      if (selectedName) selectedName.textContent = nameOf(records[index]);
    });

    track.addEventListener('click', (event) => {
      if (!bridge?.isConnected) return;
      const link = event.target.closest?.('a.area-link');
      if (!link || !link.href) return;
      event.preventDefault();
      bridge.openLink(link.href);
    });
  } else {
    nodes.push(el('p', 'notice', EMPTY_TEXT));
  }

  const actions = el('footer', 'actions');
  if (records.length) {
    const primary = el('button', 'button button-primary', 'Find products for ');
    primary.type = 'button';
    selectedName = el('span', 'selected-name', nameOf(records[0]));
    primary.append(selectedName);
    primary.addEventListener('click', () => {
      let prompt = `Find Synopsys products for ${nameOf(records[selected])}`;
      if (hasText(args.industry)) prompt += ` in ${args.industry}`;
      send(bridge, `${prompt}.`, status);
    });
    actions.append(primary);
  }
  const contact = el('button', 'button button-secondary', 'Contact sales');
  contact.type = 'button';
  contact.addEventListener('click', () => {
    const name = nameOf(records[selected]);
    send(bridge, name ? `Contact Synopsys sales about ${name}.` : 'Contact Synopsys sales.', status);
  });
  actions.append(contact);
  nodes.push(actions, status);
  block.replaceChildren(...nodes);
}

function applyTheme(block, context) {
  const theme = context?.theme;
  if (theme === 'light' || theme === 'dark') block.dataset.theme = theme;
}

export default async function decorate(block, bridge) {
  let data = PREVIEW_RESULT;
  let state = 'ok';
  if (isLive(bridge)) {
    try {
      const result = await bridge.toolResult;
      data = result?.structuredContent;
      if (result?.isError === true || !data || typeof data !== 'object') state = 'error';
    } catch {
      data = null;
      state = 'error';
    }
  }
  render(block, bridge, data, state);

  if (bridge?.isConnected) {
    applyTheme(block, bridge.hostContext);
    if (typeof bridge.onContextChange === 'function') {
      bridge.onContextChange((context) => applyTheme(block, context));
    }
    bridge.autoResize(block);
  }
}
