const SLUG = 'match-securbank-credit-card';
const BRAND = 'SecurBank';

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined && text !== null) node.textContent = text;
  return node;
}

function hasText(value) {
  return typeof value === 'string' && value.trim() !== '';
}

function safeHref(value) {
  if (!hasText(value)) return null;
  try {
    const url = new URL(value.trim());
    return url.protocol === 'https:' || url.protocol === 'tel:' ? url.href : null;
  } catch (e) {
    return null;
  }
}

function safeImage(value) {
  const href = safeHref(value);
  return href && href.startsWith('https:') ? href : null;
}

function lower(value) {
  return hasText(value) ? value.trim().toLowerCase() : '';
}

function plural(count, word) {
  return `${count} ${word}${count === 1 ? '' : 's'}`;
}

function formatMoney(value) {
  return new Intl.NumberFormat('en-US', {
    style: 'currency', currency: 'USD', maximumFractionDigits: 0,
  }).format(value);
}

function parseAmount(text) {
  const n = Number(String(text).replace(/,/g, ''));
  return Number.isFinite(n) ? n : null;
}

/* Fit rules from the surface brief: each compares one argument with one record field. */
function priorityMatches(priority, record) {
  const p = lower(priority);
  if (!p) return false;
  const desc = lower(record.description);
  if (p.includes('travel')) return lower(record.category) === 'travel';
  if (p.includes('reward')) return desc.includes('rewards');
  if (p.includes('interest') || p.includes('rate')) return desc.includes('low rate');
  if (p.includes('fee')) return desc.includes('card fees');
  return false;
}

function paymentMatches(paysInFull, record) {
  const desc = lower(record.description);
  if (paysInFull === true) return desc.includes('pay my balance off in full');
  if (paysInFull === false) return desc.includes('not likely to pay off my balance in full');
  return false;
}

function professionMatches(profession, record) {
  const arg = lower(profession);
  const target = lower(record.target_profession);
  if (!arg || !target) return false;
  return target.includes(arg) || arg.includes(target);
}

function spendFeature(spend, record) {
  const features = Array.isArray(record.features) ? record.features : [];
  return features.find((feature) => {
    if (!hasText(feature)) return false;
    const above = feature.match(/\$([\d,]+)\s+a year or more/i);
    if (above) {
      const limit = parseAmount(above[1]);
      if (limit !== null && spend >= limit) return true;
    }
    const below = feature.match(/less than \$([\d,]+)/i);
    if (below) {
      const limit = parseAmount(below[1]);
      if (limit !== null && spend < limit) return true;
    }
    return false;
  }) || null;
}

function readAnswers(args) {
  const a = args && typeof args === 'object' ? args : {};
  return {
    priority: hasText(a.spending_priority) ? a.spending_priority : null,
    profession: hasText(a.profession) ? a.profession : null,
    paysInFull: typeof a.pays_balance_in_full === 'boolean' ? a.pays_balance_in_full : null,
    spend: typeof a.annual_spend === 'number' && Number.isFinite(a.annual_spend)
      ? a.annual_spend : null,
  };
}

function scoreRecords(records, answers) {
  const scored = records.map((record, index) => {
    const badges = [];
    if (answers.priority && priorityMatches(answers.priority, record)) {
      badges.push({ rule: 'priority', label: 'Fits priority' });
    }
    if (answers.profession && professionMatches(answers.profession, record)) {
      badges.push({ rule: 'profession', label: 'Fits profession' });
    }
    if (answers.paysInFull !== null && paymentMatches(answers.paysInFull, record)) {
      badges.push({
        rule: 'payment',
        label: answers.paysInFull ? 'Fits paying in full' : 'Fits carrying a balance',
      });
    }
    return { record, index, badges };
  });
  scored.sort((x, y) => (y.badges.length - x.badges.length) || (x.index - y.index));
  return scored;
}

function ledgerMatchResult(scored, rule) {
  const result = el('dd', 'ledger-result');
  const names = scored
    .filter((s) => s.badges.some((b) => b.rule === rule) && hasText(s.record.name))
    .map((s) => s.record.name);
  if (!names.length) {
    result.textContent = 'No card’s published statement mentions this';
    return result;
  }
  result.append('Matches ');
  names.forEach((name, i) => {
    if (i > 0) result.append(i === names.length - 1 ? ' and ' : ', ');
    result.append(el('strong', 'ledger-card', name));
  });
  return result;
}

function ledgerSpendResult(records, spend) {
  const result = el('dd', 'ledger-result');
  const groups = new Map();
  records.forEach((record) => {
    const feature = spendFeature(spend, record);
    if (feature) groups.set(feature, (groups.get(feature) || 0) + 1);
  });
  if (!groups.size) {
    result.textContent = 'No card’s published statement mentions this';
    return result;
  }
  const [feature, count] = [...groups.entries()].sort((x, y) => y[1] - x[1])[0];
  const total = records.length;
  let lead;
  if (count === total) lead = total === 1 ? 'The card: ' : `All ${total} cards: `;
  else lead = `${count} of ${plural(total, 'card')}: `;
  result.append(lead, el('span', 'ledger-quote', feature));
  return result;
}

function ledgerRow(label, value, result) {
  const row = el('div', 'ledger-row');
  row.append(el('dt', 'ledger-label', label), el('dd', 'ledger-value', value), result);
  return row;
}

function buildLedger(scored, records, answers) {
  const list = el('dl', 'ledger-list');
  if (answers.priority) {
    list.append(ledgerRow('Priority', answers.priority, ledgerMatchResult(scored, 'priority')));
  }
  if (answers.profession) {
    list.append(ledgerRow('Profession', answers.profession, ledgerMatchResult(scored, 'profession')));
  }
  if (answers.paysInFull !== null) {
    list.append(ledgerRow('Pays in full', answers.paysInFull ? 'Yes' : 'No', ledgerMatchResult(scored, 'payment')));
  }
  if (answers.spend !== null) {
    list.append(ledgerRow('Annual spend', formatMoney(answers.spend), ledgerSpendResult(records, answers.spend)));
  }
  if (!list.children.length) return null;
  const section = el('section', 'ledger');
  section.setAttribute('aria-label', 'Your answers');
  section.append(list);
  return section;
}

function guardedLink(anchor, bridge) {
  anchor.addEventListener('click', (event) => {
    if (!bridge?.isConnected || !anchor.href.startsWith('https:')) return;
    event.preventDefault();
    bridge.openLink(anchor.href);
  });
}

function makeSender(bridge, status) {
  return async (prompt) => {
    if (!bridge?.isConnected) return;
    status.hidden = true;
    status.textContent = '';
    try {
      const result = await bridge.sendMessage(prompt);
      if (result?.isError === true) throw new Error('delivery failed');
    } catch (e) {
      status.textContent = 'Couldn’t send that to the chat. Try again.';
      status.hidden = false;
    }
  };
}

function buildItem(entry, position, total, send, bridge) {
  const { record, badges } = entry;
  const name = hasText(record.name) ? record.name : '';
  const item = el('li', 'item');
  item.setAttribute('aria-label', `${position} of ${total}${name ? `: ${name}` : ''}`);

  const head = el('div', 'item-head');
  const src = safeImage(record.image_url);
  if (src) {
    const img = el('img', 'item-image');
    img.src = src;
    img.alt = name;
    img.width = 96;
    img.height = 72;
    head.append(img);
  } else {
    const tile = el('div', 'item-image item-image-empty', name);
    tile.setAttribute('aria-hidden', 'true');
    head.append(tile);
  }
  const title = el('div', 'item-title');
  if (name) title.append(el('h3', 'item-name', name));
  const badgeItems = badges.map((b) => el('li', 'badge badge-highlight', b.label));
  if (hasText(record.category)) badgeItems.push(el('li', 'badge', record.category));
  if (badgeItems.length) {
    const list = el('ul', 'item-badges');
    list.setAttribute('aria-label', 'Fit and category');
    list.append(...badgeItems);
    title.append(list);
  }
  head.append(title);
  item.append(head);

  if (hasText(record.description)) item.append(el('p', 'item-description', record.description));

  const fee = hasText(record.annual_fee) ? record.annual_fee : record.price;
  const facts = el('dl', 'item-facts');
  [['Annual fee', fee], ['Purchase rate', record.purchase_interest_rate]].forEach(([label, value]) => {
    if (!hasText(value)) return;
    const pair = el('div');
    pair.append(el('dt', '', label), el('dd', '', value));
    facts.append(pair);
  });
  if (facts.children.length) item.append(facts);

  const features = Array.isArray(record.features) ? record.features.filter(hasText) : [];
  if (features.length) {
    const details = el('details', 'item-features');
    details.append(el('summary', '', `Published features (${features.length})`));
    const list = el('ul', 'feature-list');
    features.forEach((f) => list.append(el('li', '', f)));
    details.append(list);
    item.append(details);
  }

  const actions = el('div', 'item-actions');
  const cardId = hasText(record.credit_card_id) ? record.credit_card_id : null;
  if (cardId) {
    const view = el('button', 'button-primary', 'View details');
    view.type = 'button';
    view.dataset.creditCardId = cardId;
    view.setAttribute('aria-label', `View details for ${name || cardId}`);
    view.addEventListener('click', () => {
      send(`Show the published details of the ${BRAND} ${name || 'credit card'} (credit_card_id: ${cardId}).`);
    });
    actions.append(view);
  }
  const href = safeHref(record.source_url);
  if (href) {
    const link = el('a', 'item-link', 'Card page');
    link.href = href;
    if (href.startsWith('https:')) {
      link.target = '_blank';
      link.rel = 'noopener';
    }
    if (name) link.append(el('span', 'visually-hidden', ` for ${name}`));
    guardedLink(link, bridge);
    actions.append(link);
  }
  if (actions.children.length) item.append(actions);
  return item;
}

function render(block, result, bridge, failed) {
  const data = result && typeof result === 'object' ? result : {};
  const records = Array.isArray(data.records)
    ? data.records.filter((r) => r && typeof r === 'object') : [];
  const answers = readAnswers(data.arguments);
  const answered = answers.priority !== null || answers.profession !== null
    || answers.paysInFull !== null || answers.spend !== null;
  const scored = scoreRecords(records, answers);
  const fits = scored.filter((s) => s.badges.length).length;
  const total = records.length;
  const titleId = `${SLUG}-title`;

  const widget = el('div', 'widget');
  widget.setAttribute('role', 'region');
  widget.setAttribute('aria-labelledby', titleId);

  const head = el('div', 'widget-head');
  const title = el('h2', 'widget-title', answered ? `${BRAND} cards that fit your answers` : `${BRAND} credit cards`);
  title.id = titleId;
  head.append(title);
  const count = el('p', 'widget-count');
  if (failed) {
    count.textContent = 'Couldn’t load the cards. Ask again in chat.';
  } else if (!total) {
    count.textContent = `No ${BRAND} cards came back for these answers. Ask in chat to try different answers.`;
  } else if (!answered) {
    count.append(el('strong', '', plural(total, 'card')), ` from ${BRAND}.`);
  } else if (fits) {
    count.append(el('strong', '', `${fits} of ${plural(total, 'card')}`), ' fit your answers, best fit first.');
  } else {
    count.textContent = 'No card’s published statement matches your answers';
  }
  head.append(count);
  widget.append(head);

  const status = el('p', 'widget-status');
  status.setAttribute('role', 'status');
  status.hidden = true;
  const send = makeSender(bridge, status);

  if (!failed && total) {
    const ledger = answered ? buildLedger(scored, records, answers) : null;
    if (ledger) widget.append(ledger);

    const carousel = el('section', 'carousel');
    const carouselId = `${SLUG}-carousel-title`;
    carousel.setAttribute('aria-labelledby', carouselId);
    const order = answered ? ', best fit first' : '';
    const hidden = el('h3', 'visually-hidden', `${BRAND} credit cards${order}, swipe or scroll for all ${total}`);
    hidden.id = carouselId;
    const track = el('ul', 'carousel-track');
    track.tabIndex = 0;
    track.setAttribute('aria-label', `${BRAND} credit cards${order}`);
    scored.forEach((entry, i) => track.append(buildItem(entry, i + 1, total, send, bridge)));
    carousel.append(hidden, track);
    widget.append(carousel);
  }

  const footer = el('div', 'widget-actions');
  const apply = el('button', 'button-secondary', `Apply for a ${BRAND} card`);
  apply.type = 'button';
  apply.addEventListener('click', () => send(`Open the ${BRAND} credit card application form.`));
  footer.append(apply);
  widget.append(footer, status);

  block.replaceChildren(widget);
}

export default async function decorate(block, bridge) {
  const connected = bridge?.isConnected === true;
  const live = connected && bridge.hostContext?.preview !== true;

  if (connected) {
    const applyTheme = (context) => {
      const theme = context?.theme;
      if (theme === 'dark' || theme === 'light') block.dataset.theme = theme;
    };
    applyTheme(bridge.hostContext);
    bridge.onContextChange(applyTheme);
  }

  if (live) {
    let result = null;
    let failed = false;
    try {
      result = (await bridge.toolResult)?.structuredContent;
      if (!result || typeof result !== 'object') failed = true;
    } catch (e) {
      failed = true;
    }
    render(block, result, bridge, failed);
  } else {
    render(block, PREVIEW_RESULT, bridge, false);
  }

  if (connected) bridge.autoResize(block);
}
