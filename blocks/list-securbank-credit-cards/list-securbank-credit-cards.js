const SVG_NS = 'http://www.w3.org/2000/svg';
const MAX_SELECTED = 2;
let instanceCount = 0;

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined && text !== null) node.textContent = String(text);
  return node;
}

function hasValue(value) {
  if (value === undefined || value === null) return false;
  if (Array.isArray(value)) return value.length > 0;
  return String(value).trim() !== '';
}

function safeHttps(url) {
  if (!hasValue(url)) return null;
  try {
    const parsed = new URL(String(url));
    return parsed.protocol === 'https:' ? parsed.href : null;
  } catch (e) {
    return null;
  }
}

function chevron(path) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  const p = document.createElementNS(SVG_NS, 'path');
  p.setAttribute('d', path);
  svg.append(p);
  return svg;
}

function countLabel(n) {
  return n === 1 ? '1 card' : `${n} cards`;
}

function send(bridge, prompt, onError) {
  if (!bridge?.isConnected) return;
  Promise.resolve()
    .then(() => bridge.sendMessage(prompt))
    .then((result) => {
      if (result?.isError === true) onError();
    })
    .catch(() => onError());
}

function buildMedia(record) {
  const media = el('div', 'tile-media');
  const name = hasValue(record.name) ? String(record.name) : '';
  const src = safeHttps(record.image_url);
  const fallback = () => {
    media.replaceChildren();
    if (name) media.append(el('span', 'tile-image-fallback', name));
  };
  if (src) {
    const img = el('img', 'tile-image');
    img.src = src;
    img.alt = name;
    img.width = 300;
    img.height = 188;
    img.addEventListener('error', fallback, { once: true });
    media.append(img);
  } else {
    fallback();
  }
  return media;
}

function buildTile(record, index, total, ctx) {
  const name = hasValue(record.name) ? String(record.name) : '';
  const cardId = hasValue(record.credit_card_id) ? String(record.credit_card_id) : '';
  const tile = el('li', 'tile');
  tile.setAttribute('aria-roledescription', 'slide');
  tile.setAttribute('aria-label', `${index + 1} of ${total}${name ? `: ${name}` : ''}`);

  tile.append(buildMedia(record));

  const body = el('div', 'tile-body');
  const head = el('div', 'tile-head');
  if (name) head.append(el('h3', 'item-name', name));
  if (hasValue(record.category)) head.append(el('span', 'badge category-badge', record.category));
  const position = el('span', 'position', `${index + 1} of ${total}`);
  position.setAttribute('aria-hidden', 'true');
  head.append(position);
  body.append(head);

  if (hasValue(record.description)) body.append(el('p', 'item-description', record.description));

  const factDefs = [
    ['Annual fee', record.annual_fee],
    ['Purchase rate', record.purchase_interest_rate],
  ].filter(([, value]) => hasValue(value));
  if (factDefs.length) {
    const facts = el('dl', 'facts');
    if (factDefs.length === 1) facts.classList.add('facts-single');
    factDefs.forEach(([label, value]) => {
      const fact = el('div', 'fact');
      fact.append(el('dt', '', label), el('dd', '', value));
      facts.append(fact);
    });
    body.append(facts);
  }

  if (hasValue(record.intro_offer)) {
    const offer = el('div', 'offer');
    offer.append(el('span', 'badge-highlight', 'Intro offer'), el('p', 'offer-text', record.intro_offer));
    body.append(offer);
  }

  const features = Array.isArray(record.features) ? record.features.filter(hasValue) : [];
  if (features.length) {
    const terms = el('details', 'terms');
    terms.append(el('summary', '', 'Published terms'));
    const list = el('ul', 'terms-list');
    features.forEach((item) => list.append(el('li', '', item)));
    terms.append(list);
    body.append(terms);
  }
  tile.append(body);

  const actions = el('div', 'tile-actions');
  if (cardId && ctx.compareEnabled) {
    const pick = el('label', 'pick');
    const input = el('input');
    input.type = 'checkbox';
    input.name = 'compare';
    input.value = cardId;
    input.addEventListener('change', () => ctx.onPick(input, tile, name, cardId));
    pick.append(input, el('span', '', 'Select to compare'));
    actions.append(pick);
    ctx.inputs.push(input);
  }
  if (cardId) {
    const view = el('button', 'button-primary view-button', 'View card');
    view.type = 'button';
    view.setAttribute('aria-label', name ? `View ${name}` : 'View card');
    view.addEventListener('click', () => {
      const label = name ? `the ${name} (${cardId})` : `the card ${cardId}`;
      send(ctx.bridge, `Show ${label}`, () => ctx.setStatus("Couldn't send. Try again."));
    });
    actions.append(view);
  }
  if (actions.children.length) tile.append(actions);
  return tile;
}

function render(block, result, bridge) {
  const records = Array.isArray(result?.records)
    ? result.records.filter((r) => r && typeof r === 'object')
    : [];
  const total = records.length;
  instanceCount += 1;
  const titleId = `securbank-cards-title-${instanceCount}`;
  const trackId = `securbank-cards-track-${instanceCount}`;

  const section = el('section', 'card-list');
  section.setAttribute('aria-labelledby', titleId);

  const header = el('header', 'list-header');
  const titles = el('div');
  const title = el('h2', 'list-title', 'SecurBank credit cards');
  title.id = titleId;
  titles.append(title);
  if (total > 0) titles.append(el('p', 'list-count', countLabel(total)));
  header.append(titles);
  section.append(header);

  if (total === 0) {
    section.append(el('p', 'empty-state', 'No SecurBank cards matched. Try a different card type or benefit in chat.'));
    block.replaceChildren(section);
    return;
  }

  const track = el('ul', 'track');
  track.id = trackId;
  track.tabIndex = 0;
  track.setAttribute('aria-roledescription', 'carousel');
  track.setAttribute('aria-label', 'SecurBank credit cards');

  const selected = [];
  const ctx = {
    bridge,
    inputs: [],
    compareEnabled: total >= 2,
    setStatus: () => {},
    onPick: () => {},
  };

  let hint = null;
  let compareButton = null;
  const updateCompare = () => {
    if (!hint) return;
    if (selected.length === 0) hint.textContent = 'Select 2 cards to compare';
    else if (selected.length === 1) hint.textContent = '1 of 2 selected';
    else hint.textContent = '2 selected';
    compareButton.disabled = selected.length !== MAX_SELECTED;
    ctx.inputs.forEach((input) => {
      input.disabled = !input.checked && selected.length >= MAX_SELECTED;
    });
  };
  ctx.setStatus = (text) => {
    if (hint) hint.textContent = text;
  };
  ctx.onPick = (input, tile, name, cardId) => {
    if (input.checked) {
      if (selected.length >= MAX_SELECTED) {
        input.checked = false;
        return;
      }
      selected.push({ name, cardId });
      tile.classList.add('is-selected');
    } else {
      const at = selected.findIndex((s) => s.cardId === cardId);
      if (at >= 0) selected.splice(at, 1);
      tile.classList.remove('is-selected');
    }
    updateCompare();
  };

  records.forEach((record, index) => track.append(buildTile(record, index, total, ctx)));

  if (total > 1) {
    const pager = el('div', 'pager');
    const prev = el('button', 'pager-button pager-prev');
    prev.type = 'button';
    prev.setAttribute('aria-label', 'Previous cards');
    prev.setAttribute('aria-controls', trackId);
    prev.append(chevron('M15 6l-6 6 6 6'));
    const next = el('button', 'pager-button pager-next');
    next.type = 'button';
    next.setAttribute('aria-label', 'Next cards');
    next.setAttribute('aria-controls', trackId);
    next.append(chevron('M9 6l6 6-6 6'));
    pager.append(prev, next);
    header.append(pager);

    const step = () => {
      const tile = track.querySelector('.tile');
      const gap = parseFloat(getComputedStyle(track).columnGap) || 0;
      return tile ? tile.getBoundingClientRect().width + gap : track.clientWidth;
    };
    const syncPager = () => {
      const max = track.scrollWidth - track.clientWidth;
      prev.disabled = track.scrollLeft <= 1;
      next.disabled = track.scrollLeft >= max - 1;
    };
    prev.addEventListener('click', () => track.scrollBy({ left: -step(), behavior: 'smooth' }));
    next.addEventListener('click', () => track.scrollBy({ left: step(), behavior: 'smooth' }));
    track.addEventListener('scroll', syncPager, { passive: true });
    prev.disabled = true;
    requestAnimationFrame(syncPager);
    if (typeof ResizeObserver === 'function') new ResizeObserver(syncPager).observe(track);
  } else {
    track.classList.add('track-single');
  }

  section.append(track);

  if (ctx.compareEnabled && ctx.inputs.length >= 2) {
    const bar = el('footer', 'compare-bar');
    hint = el('p', 'compare-hint');
    hint.setAttribute('aria-live', 'polite');
    compareButton = el('button', 'button-secondary compare-button', 'Compare');
    compareButton.type = 'button';
    compareButton.addEventListener('click', () => {
      if (selected.length !== MAX_SELECTED) return;
      const [a, b] = selected;
      const names = `${a.name || a.cardId} and ${b.name || b.cardId}`;
      send(bridge, `Compare ${names} (${a.cardId}, ${b.cardId})`, () => ctx.setStatus("Couldn't send. Try again."));
    });
    bar.append(hint, compareButton);
    section.append(bar);
    updateCompare();
  } else {
    ctx.inputs.forEach((input) => input.closest('.pick')?.remove());
  }

  block.replaceChildren(section);
}

function applyTheme(block, context) {
  const theme = context?.theme;
  if (theme === 'light' || theme === 'dark') block.dataset.theme = theme;
}

export default async function decorate(block, bridge) {
  const connected = Boolean(bridge?.isConnected);
  const preview = connected && bridge.hostContext?.preview === true;
  let result = PREVIEW_RESULT;
  if (connected && !preview) {
    try {
      result = (await bridge.toolResult)?.structuredContent ?? { arguments: {}, records: [] };
    } catch (e) {
      result = null;
    }
  }

  if (connected) {
    applyTheme(block, bridge.hostContext);
    bridge.onContextChange((context) => applyTheme(block, context));
  }

  if (result === null) {
    const section = el('section', 'card-list');
    section.append(
      el('h2', 'list-title', 'SecurBank credit cards'),
      el('p', 'empty-state', "Couldn't load SecurBank cards. Ask again in chat."),
    );
    block.replaceChildren(section);
  } else {
    render(block, result, bridge);
  }

  if (connected) bridge.autoResize(block);
}
