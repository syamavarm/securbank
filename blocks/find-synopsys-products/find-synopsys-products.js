function text(value) {
  if (value === undefined || value === null) return '';
  if (typeof value === 'string') return value.trim() ? value : '';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  return '';
}

function list(value) {
  if (Array.isArray(value)) return value.map(text).filter(Boolean);
  const single = text(value);
  return single ? [single] : [];
}

function safeHttps(url) {
  const value = text(url);
  if (!value) return '';
  try {
    const parsed = new URL(value);
    return parsed.protocol === 'https:' ? parsed.href : '';
  } catch (e) {
    return '';
  }
}

function domKey(value) {
  return String(value).toLowerCase().replace(/[^a-z0-9_-]+/g, '-');
}

function isConnected(bridge) {
  return Boolean(bridge && bridge.isConnected);
}

async function deliver(bridge, prompt, onFailure) {
  if (!isConnected(bridge) || !prompt) return;
  try {
    const result = await bridge.sendMessage(prompt);
    if (result && result.isError === true) onFailure();
  } catch (e) {
    onFailure();
  }
}

function renderHeader(args, count) {
  const head = el('header', 'result-head');
  const family = text(args.product_family);
  const industry = text(args.industry);
  const title = el('h2', 'result-title', family ? `${family} products` : 'Synopsys products');
  title.id = 'result-title';
  head.append(title);

  const meta = el('p', 'result-meta');
  if (count !== null) {
    meta.append(el('span', 'result-count', `${count} ${count === 1 ? 'product' : 'products'}`));
  }
  [['Family', family], ['Industry', industry]].forEach(([key, value]) => {
    if (!value) return;
    const chip = el('span', 'filter-chip');
    chip.append(el('span', 'filter-key', key), document.createTextNode(` ${value}`));
    meta.append(chip);
  });
  if (meta.childNodes.length) head.append(meta);
  return head;
}

function renderMedia(record, name) {
  const src = safeHttps(record.image_url);
  if (src) {
    const media = el('div', 'item-media');
    const img = el('img', 'item-image');
    img.src = src;
    img.alt = name;
    img.width = 120;
    img.height = 90;
    img.loading = 'eager';
    img.decoding = 'async';
    img.addEventListener('error', () => {
      media.replaceWith(renderMedia({ image_url: null }, name));
    }, { once: true });
    media.append(img);
    return media;
  }
  const media = el('div', 'item-media item-media-empty');
  media.append(chipIcon(), el('span', 'fallback-label', 'No image published'));
  return media;
}

function renderCard(record, index, total, ctx) {
  const name = text(record.name) || text(record.product_id) || text(record.id);
  const productId = text(record.product_id);
  const key = domKey(productId || text(record.id) || `item-${index + 1}`);
  const item = el('li', 'item');
  item.id = `product-${key}`;
  item.setAttribute('aria-roledescription', 'slide');
  item.setAttribute('aria-label', `${index + 1} of ${total}: ${name}`);

  const body = el('article', 'item-body');
  body.setAttribute('aria-labelledby', `name-${key}`);

  const head = el('div', 'item-head');
  const heading = el('div', 'item-heading');
  const title = el('h3', 'item-name', name);
  title.id = `name-${key}`;
  heading.append(title);
  const family = text(record.product_family);
  if (family) heading.append(el('span', 'badge', family));
  head.append(renderMedia(record, name), heading);
  body.append(head);

  const industries = list(record.industries);
  if (industries.length) {
    const line = el('p', 'item-industries');
    line.append(el('span', 'meta-label', 'Industries'), document.createTextNode(` ${industries.join(', ')}`));
    body.append(line);
  }

  const description = text(record.description);
  if (description) body.append(el('p', 'item-description', description));

  const features = list(record.features);
  if (features.length) {
    const details = el('details', 'item-features');
    const summary = el('summary');
    summary.append(chevronIcon(), el('span', '', `Features (${features.length})`));
    const ul = el('ul', 'feature-list');
    ul.tabIndex = 0;
    ul.setAttribute('aria-label', `${name} features`);
    features.forEach((feature) => ul.append(el('li', '', feature)));
    details.append(summary, ul);
    body.append(details);
  }

  if (productId) {
    const actions = el('div', 'item-actions');
    const view = el('button', 'button-primary', 'View details');
    view.type = 'button';
    view.dataset.productId = productId;
    view.addEventListener('click', () => {
      deliver(ctx.bridge, `Show details for ${name} (${productId})`, ctx.onFailure);
    });
    actions.append(view);

    if (ctx.compareEnabled) {
      const label = el('label', 'compare-toggle');
      const input = el('input', 'compare-input');
      input.type = 'checkbox';
      input.value = productId;
      input.setAttribute('aria-label', `Select ${name} to compare`);
      input.addEventListener('change', () => ctx.onToggle(input, { productId, name }));
      label.append(input, toggleIcon(), el('span', '', 'Compare'));
      actions.append(label);
      ctx.inputs.push(input);
    }
    body.append(actions);
  }

  item.append(body);
  return item;
}

function renderMessage(block, message, args) {
  const root = el('div', 'widget');
  root.append(renderHeader(args || {}, null), el('p', 'state-message', message));
  block.replaceChildren(root);
}

function renderLoading(block) {
  const root = el('div', 'widget widget-loading');
  root.setAttribute('aria-busy', 'true');
  const rail = el('div', 'skeleton skeleton-rail');
  const track = el('div', 'skeleton-track');
  for (let i = 0; i < 3; i += 1) track.append(el('div', 'skeleton skeleton-card'));
  root.append(rail, track);
  block.replaceChildren(root);
}

function render(block, data, bridge) {
  const args = data && typeof data.arguments === 'object' && data.arguments ? data.arguments : {};
  const records = Array.isArray(data && data.records)
    ? data.records.filter((r) => r && typeof r === 'object')
    : [];

  const root = el('div', 'widget');
  root.setAttribute('aria-labelledby', 'result-title');
  root.append(renderHeader(args, records.length));

  if (!records.length) {
    root.append(el('p', 'state-message', 'No Synopsys products match these filters.'));
    block.replaceChildren(root);
    return;
  }

  const selected = [];
  const compareable = records.filter((r) => text(r.product_id)).length;
  const actionStatus = el('p', 'action-status');
  actionStatus.setAttribute('role', 'status');
  actionStatus.hidden = true;
  const ctx = {
    bridge,
    inputs: [],
    compareEnabled: compareable >= MAX_COMPARE,
    onFailure: () => {
      actionStatus.textContent = "Couldn't send that request. Try again in the chat.";
      actionStatus.hidden = false;
    },
    onToggle: null,
  };

  const status = el('p', 'compare-status', 'Select two products to compare');
  status.setAttribute('aria-live', 'polite');
  const compareButton = el('button', 'button-secondary compare-button', 'Compare');
  compareButton.type = 'button';
  compareButton.disabled = true;

  const syncCompare = () => {
    if (selected.length === 0) status.textContent = 'Select two products to compare';
    else if (selected.length === 1) status.textContent = '1 selected — choose one more';
    else status.textContent = '2 selected';
    compareButton.disabled = selected.length !== MAX_COMPARE;
    ctx.inputs.forEach((input) => {
      input.disabled = !input.checked && selected.length >= MAX_COMPARE;
      input.closest('.compare-toggle').classList.toggle('is-disabled', input.disabled);
    });
  };

  ctx.onToggle = (input, item) => {
    const at = selected.findIndex((s) => s.productId === item.productId);
    if (input.checked && at === -1) {
      if (selected.length >= MAX_COMPARE) {
        input.checked = false;
      } else {
        selected.push(item);
      }
    } else if (!input.checked && at !== -1) {
      selected.splice(at, 1);
    }
    syncCompare();
  };

  compareButton.addEventListener('click', () => {
    if (selected.length !== MAX_COMPARE) return;
    const [a, b] = selected;
    deliver(bridge, `Compare ${a.name} and ${b.name} (${a.productId}, ${b.productId})`, ctx.onFailure);
  });

  const family = text(args.product_family);
  const nav = el('nav', 'rail');
  nav.setAttribute('aria-label', 'Products in this result');
  const railList = el('ul', 'rail-list');
  nav.append(railList);

  const carousel = el('section', 'carousel');
  carousel.setAttribute('aria-roledescription', 'carousel');
  carousel.setAttribute('aria-label', family ? `${family} products` : 'Synopsys products');
  const track = el('ul', 'track');
  track.tabIndex = 0;
  track.setAttribute('aria-label', 'Product cards, scroll sideways');
  carousel.append(track);

  const items = records.map((record, index) => renderCard(record, index, records.length, ctx));
  const chips = items.map((item, index) => {
    const li = el('li');
    const chip = el('a', 'rail-chip', text(records[index].name) || text(records[index].product_id) || text(records[index].id));
    chip.href = `#${item.id}`;
    if (index === 0) chip.setAttribute('aria-current', 'true');
    chip.addEventListener('click', (event) => {
      event.preventDefault();
      track.scrollTo({ left: item.offsetLeft - items[0].offsetLeft });
    });
    li.append(chip);
    railList.append(li);
    return chip;
  });
  track.append(...items);

  let current = 0;
  const setCurrent = (index) => {
    if (index === current || !chips[index]) return;
    chips[current].removeAttribute('aria-current');
    chips[index].setAttribute('aria-current', 'true');
    current = index;
    const chip = chips[index];
    const left = chip.offsetLeft - nav.offsetLeft;
    if (left < nav.scrollLeft || left + chip.offsetWidth > nav.scrollLeft + nav.clientWidth) {
      nav.scrollTo({ left: Math.max(0, left - 16) });
    }
  };
  let frame = 0;
  track.addEventListener('scroll', () => {
    if (frame) return;
    frame = requestAnimationFrame(() => {
      frame = 0;
      const base = items[0].offsetLeft;
      let best = 0;
      let bestDistance = Infinity;
      items.forEach((item, index) => {
        const distance = Math.abs(item.offsetLeft - base - track.scrollLeft);
        if (distance < bestDistance) {
          bestDistance = distance;
          best = index;
        }
      });
      if (track.scrollLeft + track.clientWidth >= track.scrollWidth - 2) best = items.length - 1;
      setCurrent(best);
    });
  }, { passive: true });

  root.append(nav, carousel);

  if (ctx.compareEnabled) {
    const footer = el('footer', 'compare-bar');
    footer.append(status, compareButton);
    root.append(footer);
  }
  root.append(actionStatus);
  block.replaceChildren(root);
}

export default async function decorate(block, bridge) {
  const connected = isConnected(bridge);
  const preview = connected && bridge.hostContext && bridge.hostContext.preview === true;

  if (connected) {
    const applyTheme = (context) => {
      const theme = context && context.theme;
      if (theme === 'light' || theme === 'dark') block.dataset.theme = theme;
    };
    applyTheme(bridge.hostContext);
    if (typeof bridge.onContextChange === 'function') bridge.onContextChange(applyTheme);
  }

  if (!connected || preview) {
    render(block, PREVIEW_RESULT, bridge);
  } else {
    renderLoading(block);
    try {
      const result = await bridge.toolResult;
      const data = result && result.structuredContent;
      if (data && typeof data === 'object') render(block, data, bridge);
      else renderMessage(block, "Couldn't load products. Ask again in the chat.", {});
    } catch (e) {
      renderMessage(block, "Couldn't load products. Ask again in the chat.", {});
    }
  }

  if (connected && typeof bridge.autoResize === 'function') bridge.autoResize(block);
}
